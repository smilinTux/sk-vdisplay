#!/bin/sh
# install.sh <instance-dir> [--no-root] [--firewall-zone ZONE] [--enable]
#
# Builds and installs sk-vdisplay for the current user, then renders the
# per-machine config from an instance directory (see examples/instance):
#   * ~/.config/sk-vdisplay/instance        -> symlink to the instance dir
#   * ~/.config/sk-vdisplay/sunshine/<name>/ Sunshine config per screen
#   * ~/.config/pipewire/pipewire.conf.d/sk-vdisplay-mics.conf
#   * /etc/modprobe.d + /etc/modules-load.d for evdi and v4l2loopback (sudo; skip with --no-root)
#   * firewalld ports for Sunshine + SRT camera listeners (only with --firewall-zone)
#   * --enable: enable + start sk-vdisplay@, sk-sunshine@ and listener sk-cam@ units
#
# Set SUNSHINE_USER / SUNSHINE_PASSWORD to create Sunshine web UI credentials
# for screens that do not have them yet. Never commit them to the instance repo.
set -eu
here=$(cd "$(dirname "$0")" && pwd)
[ $# -ge 1 ] || { sed -n '2,15p' "$0"; exit 2; }
inst=$(cd "$1" && pwd); shift
root=1; zone=""; enable=0
while [ $# -gt 0 ]; do
	case "$1" in
		--no-root) root=0 ;;
		--firewall-zone) zone="$2"; shift ;;
		--enable) enable=1 ;;
		*) echo "unknown option $1" >&2; exit 2 ;;
	esac
	shift
done

SK_VDISPLAY_INSTANCE_DIR="$inst"; export SK_VDISPLAY_INSTANCE_DIR
. "$here/bin/sk-vdisplay-common.sh"
skv_load_conf
"$here/tests/test-config.sh" "$inst"

echo "== build + install binaries and units"
make -C "$here" install >/dev/null
mkdir -p "$SKV_STATE"
ln -sfn "$inst" "$SKV_STATE/instance"

nscreens=$(skv_screens | wc -l)

echo "== Sunshine configs ($nscreens screens)"
skv_screens | while read -r name mode _pos port; do
	d="$SKV_STATE/sunshine/$name"
	mkdir -p "$d"
	cat > "$d/sunshine.conf" <<EOF
# generated by sk-vdisplay install.sh from screens.conf; output_name is set at start
sunshine_name = $HOST_LABEL-$name
port = $port
capture = x11
encoder = ${SUNSHINE_ENCODER:-vaapi}
adapter_name = ${SUNSHINE_ADAPTER:-/dev/dri/renderD128}
origin_web_ui_allowed = lan
file_apps = $d/apps.json
file_state = $d/sunshine_state.json
credentials_file = $d/sunshine_state.json
pkey = $d/credentials/cakey.pem
cert = $d/credentials/cacert.pem
log_path = $d/sunshine.log
EOF
	[ -f "$d/apps.json" ] || cat > "$d/apps.json" <<'EOF'
{
  "env": { "PATH": "$(PATH):$(HOME)/.local/bin" },
  "apps": [ { "name": "Desktop", "image-path": "desktop.png" } ]
}
EOF
	if [ -n "${SUNSHINE_PASSWORD:-}" ] && ! grep -q '"username"' "$d/sunshine_state.json" 2>/dev/null; then
		sunshine "$d/sunshine.conf" --creds "${SUNSHINE_USER:-admin}" "$SUNSHINE_PASSWORD" >/dev/null 2>&1
		echo "   $name: web UI credentials created"
	fi
	echo "   $name: $HOST_LABEL-$name, $mode, web UI https://<host>:$((port + 1))"
done

echo "== PipeWire device mics"
mics="$HOME/.config/pipewire/pipewire.conf.d/sk-vdisplay-mics.conf"
mkdir -p "$(dirname "$mics")"
{
	echo "# generated by sk-vdisplay install.sh: a stream plays into '<Label> Mic In',"
	echo "# apps use '<Label> Mic' as their microphone."
	echo "context.modules = ["
	for f in "$inst"/cams/*.env; do
		[ -f "$f" ] || continue
		n=$(basename "$f" .env)
		( LABEL=""; AUDIO=1; . "$f"; [ "${AUDIO:-1}" = 1 ] || exit 0; l="${LABEL:-$n}"
		cat <<EOF
  { name = libpipewire-module-loopback
    args = {
      node.description = "$l Mic"
      capture.props = { node.name = "sk_${n}_mic_in" media.class = "Audio/Sink" audio.position = [ FL FR ] node.description = "$l Mic In" }
      playback.props = { node.name = "sk_${n}_mic" media.class = "Audio/Source" audio.position = [ FL FR ] node.description = "$l Mic" }
    }
  }
EOF
		)
	done
	echo "]"
} > "$mics"

if [ "$root" = 1 ]; then
	echo "== kernel modules (sudo)"
	nr=""; labels=""; caps=""
	for f in "$inst"/cams/*.env; do
		[ -f "$f" ] || continue
		n=$(basename "$f" .env)
		eval "$(LABEL=""; . "$f"; printf 'dev=%s; lab=%s' "$DEV" "${LABEL:-$n}")"
		nr="${nr:+$nr,}${dev#/dev/video}"; labels="${labels:+$labels,}$lab Cam"; caps="${caps:+$caps,}1"
	done
	echo "options evdi initial_device_count=$((nscreens + 1))" | sudo tee /etc/modprobe.d/sk-vdisplay-evdi.conf >/dev/null
	echo evdi | sudo tee /etc/modules-load.d/sk-vdisplay-evdi.conf >/dev/null
	if [ -n "$nr" ]; then
		ncams=$(echo "$nr" | tr ',' '\n' | wc -l)
		echo "options v4l2loopback devices=$ncams video_nr=$nr card_label=\"$labels\" exclusive_caps=$caps" \
			| sudo tee /etc/modprobe.d/sk-vdisplay-v4l2loopback.conf >/dev/null
		echo v4l2loopback | sudo tee /etc/modules-load.d/sk-vdisplay-v4l2loopback.conf >/dev/null
	fi
	echo "   written; takes effect at next boot (or reload the modules)"
fi

if [ -n "$zone" ]; then
	echo "== firewalld zone $zone"
	ports=$(skv_screens | while read -r _n _m _p b; do
		echo "$((b-5))/tcp $b/tcp $((b+1))/tcp $((b+21))/tcp $((b+9))-$((b+11))/udp $((b+13))/udp $((b+21))/udp"
	done)
	for f in "$inst"/cams/*.env; do
		[ -f "$f" ] || continue
		p=$(. "$f"; echo "$SRC" | sed -n 's|^srt://0\.0\.0\.0:\([0-9]*\).*mode=listener.*|\1|p')
		[ -n "$p" ] && ports="$ports $p/udp"
	done
	for p in $ports; do sudo firewall-cmd -q --permanent --zone="$zone" --add-port="$p"; done
	sudo firewall-cmd -q --reload
	echo "   opened: $ports"
fi

systemctl --user daemon-reload
if [ "$enable" = 1 ]; then
	echo "== enable units"
	skv_screens | while read -r name _rest; do
		systemctl --user enable --now "sk-vdisplay@$name" "sk-sunshine@$name" >/dev/null 2>&1
		echo "   sk-vdisplay@$name sk-sunshine@$name"
	done
	for f in "$inst"/cams/*.env; do
		[ -f "$f" ] || continue
		n=$(basename "$f" .env)
		if (. "$f"; case "$SRC" in *mode=listener*) exit 0 ;; *) exit 1 ;; esac); then
			systemctl --user enable --now "sk-cam@$n" >/dev/null 2>&1 && echo "   sk-cam@$n (listener)"
		fi
	done
	systemctl --user restart pipewire pipewire-pulse wireplumber
fi
echo "done."
